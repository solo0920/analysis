#!/usr/bin/env node
// 為所有 assets/*.js 產生短 content hash；bootstrap 以 ?v=<hash> 載入，搭配長快取。
"use strict";

const fs = require("fs");
const path = require("path");
const crypto = require("crypto");

const root = path.resolve(__dirname, "../..");
const assetsDir = path.join(root, "site", "assets");
const out = path.join(assetsDir, "asset-manifest.js");
const manifest = {};

function walk(dir) {
  for (const entry of fs.readdirSync(dir, { withFileTypes: true })) {
    const file = path.join(dir, entry.name);
    if (entry.isDirectory()) {
      walk(file);
    } else if (entry.name.endsWith(".js") && file !== out) {
      const relative = path.relative(assetsDir, file).split(path.sep).join("/");
      const hash = crypto.createHash("sha256").update(fs.readFileSync(file)).digest("hex").slice(0, 12);
      manifest[relative] = hash;
    }
  }
}

walk(assetsDir);
const keys = Object.keys(manifest).sort();
const body = keys.map(function (key) {
  return "  " + JSON.stringify(key) + ": " + JSON.stringify(manifest[key]);
}).join(",\n");
fs.writeFileSync(out, "/* generated by build-asset-manifest.js */\nwindow.__ASSET_MANIFEST__ = {\n" + body + "\n};\n");
console.log("asset manifest: " + keys.length + " JS files");
